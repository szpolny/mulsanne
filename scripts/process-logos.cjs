// Usage: node scripts/process-logos.cjs <raw-svg-dir> src/lib/logos/logos.ts <preview.html>
// Raw files: see src/lib/logos/CREDITS.md for sources.
// Extracts <path> geometry from downloaded SVGs, crops to the emblem and maps
// colours to monochrome (dark/colour -> currentColor, white -> cutout).
const fs = require("fs");
const path = require("path");
const [rawDir, outTs, previewHtml] = process.argv.slice(2);

const CONFIG = {
  oreca: { keep: [0, 1], viewBox: "0 0 86 88" },
  mercedes: { viewBox: "0 0 1000 1000" },
  lexus: { viewBox: "0 0 131 96.3" },
  // "IF" block of the badge, without the script lettering above it.
  isotta: { viewBox: "77 310 481 501" },
};

function attr(tag, name) {
  const m = tag.match(new RegExp(String.raw`\s${name}="([^"]*)"`));
  return m ? m[1] : null;
}
function styleProp(tag, name) {
  const st = attr(tag, "style") || "";
  const m = st.match(new RegExp(String.raw`${name}\s*:\s*([^;]+)`));
  return m ? m[1].trim() : null;
}
function isLight(color) {
  if (!color) return false;
  let c = color.toLowerCase();
  if (c === "white") return true;
  if (/^#[0-9a-f]{3}$/.test(c)) c = "#" + [...c.slice(1)].map((x) => x + x).join("");
  if (!/^#[0-9a-f]{6}$/.test(c)) return false;
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(c.slice(i, i + 2), 16));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b > 200;
}

const out = {};
for (const [name, cfg] of Object.entries(CONFIG)) {
  const file = path.join(rawDir, `${name}.svg`);
  if (!fs.existsSync(file) || fs.statSync(file).size === 0) {
    console.log("skip (missing)", name);
    continue;
  }
  const svg = fs.readFileSync(file, "utf8");
  if (/<script|javascript:|<foreignObject|<image|\son\w+=/i.test(svg)) throw new Error(`${name}: unexpected active content`);
  const viewBox = cfg.viewBox || (svg.match(/viewBox="([^"]+)"/) || [])[1];
  if (!viewBox) throw new Error(`${name}: no viewBox`);
  const tags = svg.match(/<path\b[^>]*>/gs) || [];
  const paths = tags
    .map((tag, i) => {
      const d = (attr(tag, "d") || "").replace(/\s+/g, " ").trim();
      const fill = attr(tag, "fill") || styleProp(tag, "fill");
      const rule = attr(tag, "fill-rule") || styleProp(tag, "fill-rule");
      return { i, d, cutout: isLight(fill), evenodd: rule === "evenodd", none: fill === "none" };
    })
    .filter((p) => p.d && !p.none && (!cfg.keep || cfg.keep.includes(p.i)))
    .map(({ d, cutout, evenodd }) => ({ d, ...(cutout ? { cutout: true } : {}), ...(evenodd ? { evenodd: true } : {}) }));
  if (!/^[MmLlHhVvCcSsQqTtAaZz0-9.,\s+eE-]+$/.test(paths.map((p) => p.d).join(""))) throw new Error(`${name}: unexpected path data`);
  out[name] = { viewBox, paths };
  console.log(name, viewBox, paths.length, "paths", paths.filter((p) => p.cutout).length, "cutouts");
}

const ts = `// Generated by scripts/process-logos.cjs from Wikimedia Commons files (see CREDITS.md). Do not edit by hand.
export interface LogoPath { d: string; cutout?: boolean; evenodd?: boolean }
export interface LogoData { viewBox: string; paths: LogoPath[] }

export const LOGOS: Record<string, LogoData> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(outTs, ts);

const cells = Object.entries(out)
  .map(([n, l]) => {
    const g = (fg, bg) =>
      `<svg viewBox="${l.viewBox}" width="${fg}" height="${(fg * +l.viewBox.split(" ")[3]) / +l.viewBox.split(" ")[2]}" style="color:#fff">${l.paths
        .map((p) => `<path d="${p.d}" fill="${p.cutout ? bg : "currentColor"}"${p.evenodd ? ' fill-rule="evenodd"' : ""}/>`)
        .join("")}</svg>`;
    return `<div style="display:flex;gap:16px;align-items:center;padding:8px;color:#aaa;font:14px sans-serif"><b style="width:80px">${n}</b>${g(96, "#0e0e11")}${g(32, "#0e0e11")}${g(16, "#0e0e11")}<span style="background:#e3101f;padding:4px">${g(16, "#e3101f")}</span></div>`;
  })
  .join("");
fs.writeFileSync(previewHtml, `<!doctype html><body style="background:#0e0e11;margin:20px">${cells}</body>`);
